def get_translation(text: str, lang: str) -> str:
    """
    Get pre-translated text for the given language.
    Falls back to original text if translation not found.
    """
    if lang == "english" or lang == "en":
        return text
    
    # Handle language aliases
    if lang == "tenglish":
        lang = "telugu"
    elif lang == "hinglish":
        lang = "hindi"
    
    # Normalize whitespace in text (collapse multiple spaces/newlines to single space)
    import re
    normalized_text = re.sub(r'\s+', ' ', text.strip())
    
    translations = UI_TRANSLATIONS.get(lang, {})
    result = translations.get(normalized_text, None)
    
    if result:
        return result
    
    # Also try the original text as-is
    return translations.get(text, text)
